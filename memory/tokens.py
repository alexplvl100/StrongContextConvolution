"""
SCC — подсчёт токенов
======================

Единственное место, где в проекте считается объём. Одна реализация на всех:
если считать по-разному в ядре и в памяти, замеры уровней окажутся
несравнимыми, и решение о переходе между уровнями будет приниматься по
несогласованным числам.

СПОСОБ ПОДСЧЁТА И ЕГО ТОЧНОСТЬ
--------------------------------
Используется эвристика «4 символа = 1 токен». Точность ограничена: замерено на
живой сессии, что **эвристика занижает на треть** (302 380 по эвристике против
401 428 по счёту API). Причина — код, пути и JSON: там токен занимает 2–3
символа, а не 4.

Этого достаточно для СРАВНЕНИЯ уровней между собой: систематическая ошибка
сокращается, и «средняя память вдвое больше короткой» остаётся верным. Для
прогноза стоимости в деньгах — нет, там нужен токенизатор модели.

    from memory import tokens
    tokens.estimate("привет мир")        # 3 (11 символов / 4, округление вверх)
    tokens.count_chunks([c1, c2])        # суммарный объём стака
"""

from __future__ import annotations

from typing import Iterable

# ── Константа эвристики ──────────────────────────────────────────────────────
# Ровно та же, что в ядре (core/token-meter, 4 символа): согласованность важнее
# точности, иначе уровни несравнимы.
CHARS_PER_TOKEN = 4


def estimate(text: str) -> int:
    """
    Оценить токены текста. Пустой текст — 0, не 1.

    Округление вверх: недооценить объём опаснее, чем переоценить — недооценка
    означает, что порог сработает позже, чем следовало.
    """
    if not text:
        return 0
    return -(-len(text) // CHARS_PER_TOKEN)


def count_chunks(chunks: Iterable[object]) -> int:
    """
    Суммарный объём набора чанков.

    Чанк может быть словарём (как в chain.json) или объектом с полем `content`.
    Считается поле `content`: остальные поля — метаданные, в контекст они не
    попадают.
    """
    total = 0
    for chunk in chunks:
        if isinstance(chunk, dict):
            content = chunk.get("content", "")
        else:
            content = getattr(chunk, "content", "")
        total += estimate(str(content))
    return total


def would_exceed(text: str, threshold: int) -> bool:
    """Превышает ли текст порог. Порог в токенах, текст — в символах."""
    return estimate(text) > threshold


def format_report(rows: Iterable[tuple[str, int]]) -> str:
    """Собрать таблицу замера: строки вида (подпись, токены)."""
    lines = [f"{'уровень':<22} {'токенов':>10}"]
    lines.append("-" * 34)
    total = 0
    for label, value in rows:
        lines.append(f"{label:<22} {value:>10}")
        total += value
    lines.append("-" * 34)
    lines.append(f"{'ИТОГО':<22} {total:>10}")
    return "\n".join(lines)
