"""
SCC — промт доступа к CAS
===========================

Формирует **инструкцию CAS** — третью часть **HEAD**. HEAD стоит в начале
контекста, перед памятью, и не сжимается (инвариант 8). Агент видит инструкцию
до того, как прочитает чанки, поэтому уже знает: ссылки `CAS?{хеш}?`
разрешаются прямым обращением к базе.

ПОЧЕМУ ОТДЕЛЬНЫЙ ПРОМТ
-----------------------
Без него ссылка `CAS?a1b2c3d4?` в чанке выглядит как мусор: агент не знает ни
что это, ни как получить значение. Промт объясняет три вещи — что такое ссылка,
чем она полезна и каким инструментом её разрешать.

ПОЧЕМУ ДО ЧАНКОВ, А НЕ ПОСЛЕ
------------------------------
Агент читает контекст сверху вниз. Инструкция, стоящая ПОСЛЕ чанков, попадёт в
поле зрения уже после того, как он наткнётся на непонятные ссылки, — и первая
реакция будет «данные потеряны». Инструкция в составе HEAD — перед памятью —
предотвращает это.

ПОРЯДОК В КОНТЕКСТЕ
--------------------
Инструкция CAS — часть HEAD (METHODOLOGY_HEAD.md). HEAD стоит перед памятью
целиком и НЕ сжимается, не обрабатывается CAS и не уходит в архив
(инвариант 8):

    +------------------------------------------------+
    | HEAD — не сжимается, не уходит в архив          |
    |   роль агента                                   |
    |   инструкция Архивариуса  <- если архив есть    |
    |   ИНСТРУКЦИЯ CAS          <- ЭТОТ БЛОК           |
    +------------------------------------------------+
    | средняя память (чанки)                          |
    +------------------------------------------------+
    | короткая память                                 |
    +------------------------------------------------+

ПОЧЕМУ ОБРАЩЕНИЕ ОБЯЗАТЕЛЬНО ПРЯМОЕ
-------------------------------------
Точное значение обязано возвращаться побайтово. Архивариус — агент с языковой
моделью, и любой его пересказ внёс бы искажение: путь стал бы «похожим», хеш —
«приблизительно верным». Архивариус к CAS **не имеет отношения**: его область —
архив чанков. Поэтому доступ к CAS идёт **в обход модели**, вызовом
функции. Архивариус к точным данным не привлекается вовсе.

    from memory.cas_prompt import build_cas_prompt
    text = build_cas_prompt()               # общая форма
    text = build_cas_prompt(reference_count=5)   # если ссылок известно сколько
"""

from __future__ import annotations

# ── Шаблон промта ────────────────────────────────────────────────────────────
# Формулировка адресована агенту, поэтому говорит, что ДЕЛАТЬ, а не описывает
# устройство хранилища.
CAS_PROMPT_TEMPLATE = """[ТОЧНЫЕ ДАННЫЕ — CAS]

В чанках ниже встречаются ссылки вида CAS?{{хеш}}?, например CAS?a1b2c3d4?.
Это НЕ потерянные данные и НЕ ошибка. Так обозначено точное значение (путь,
идентификатор, число, дата), вынесенное в хранилище CAS
(content-addressed store) ради экономии места: сама ссылка занимает 13
символов, а значение — десятки.

КАК ПОЛУЧИТЬ ЗНАЧЕНИЕ:
    Обращайся к CAS НАПРЯМУЮ, вызовом функции, а не через Архивариуса.
    Обход Архивариуса ОБЯЗАТЕЛЕН: это агент с языковой моделью, и его
    пересказ исказил бы точное значение. Точные данные обязаны
    возвращаться побайтово, поэтому путь к ним не проходит ни через одну
    модель.

    Инструменты доступа (модуль memory.cas):
      resolve_many([хеш, ...])  -> словарь {{хеш: оригинал}} одним запросом
      restore(хеш)              -> оригинал по одному хешу
      references_in(текст)      -> список ссылок, найденных в чанке

    Порядок работы: возьми хеши, которые нужно разрешить, и вызови
    resolve_many. Всё, что нужно, приходит в одном ответе.

ЧЕГО НЕ ДЕЛАТЬ:
    Не выводи ссылку как значение и не догадывайся, что за ней стоит.
    Не проси Архивариуса «расшифровать» ссылку — он для этого не
    предназначен.
    Если хеш не разрешился — скажи об этом прямо, не подставляй
    правдоподобное значение.
{extra}"""

# Дополнение, когда число ссылок известно: конкретика помогает агенту оценить
# объём работы до первого обращения.
COUNT_NOTE = """
В текущем контексте ссылок: {count}. Для получения всех значений достаточно
одного вызова resolve_many со списком этих хешей.
"""


def build_cas_prompt(reference_count: int | None = None) -> str:
    """
    Собрать промт доступа к CAS.

    `reference_count` — число ссылок в контексте, если оно известно заранее.
    None означает «неизвестно»: тогда блок не называет число, чтобы не вводить
    агента в заблуждение неверной цифрой.

    Пустая строка, если ссылок заведомо нет (`reference_count == 0`): упоминать
    механизм, которым не воспользуются, значит занимать контекст впустую — а вся
    задача CAS в его экономии.
    """
    if reference_count == 0:
        return ""
    extra = COUNT_NOTE.format(count=reference_count) if reference_count else ""
    return CAS_PROMPT_TEMPLATE.format(extra=extra)


def cas_token_cost(reference_count: int | None = None, chars_per_token: int = 4) -> int:
    """
    Стоимость промта CAS в токенах (эвристика, как везде в проекте).

    Нужна для честного замера: промт занимает место в контексте, и это место
    должно быть видно в таблице расхода, а не растворяться в «прочем».
    """
    text = build_cas_prompt(reference_count)
    if not text:
        return 0
    return -(-len(text) // chars_per_token)
