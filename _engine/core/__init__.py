"""
SCC — ядро свёртки сильного контекста
======================================

Пакет содержит инструменты ядра: конвертер журнала в поток событий, прогон
трёх этапов свёртки, чанкование и проверку пригодности.

ОСОБЕННОСТЬ: модули здесь — САМОСТОЯТЕЛЬНЫЕ СКРИПТЫ, а не библиотека
--------------------------------------------------------------------
Каждый файл запускается напрямую (`python3 core/scc_run.py ...`) и не требует
импорта соседей. Это сделано осознанно: ядро должно работать из своей
директории, а тесты загружают модули через `importlib`, не полагаясь на
структуру пакета.

Наличие `__init__.py` даёт возможность импортировать ядро как пакет — например,
`from core import scc_chunk` — когда это удобнее CLI. Зависимостей от этого
нет: ни один модуль ядра не импортирует другой.

ГРАНИЦА ОТВЕТСТВЕННОСТИ
------------------------
Ядро СОЗДАЁТ чанк и НЕ ЗНАЕТ, куда он попадёт. Хранение и перемещение чанков —
задача пакета `memory/`, который, наоборот, не знает, как чанк создан. Граница
проверяется тестом `tests/test_memory.py`: память не импортирует ядро.

Языковая модель используется ТОЛЬКО здесь (`scc_run.py`, `scc_usability.py`).
В `memory/` вызовов модели нет — это инвариант 3 из METHODOLOGY_MEMORY.md.

Состав:

    scc_events.py     журнал DSH -> поток событий       (без LLM)
    scc_run.py        этапы I/II/III свёртки            (LLM)
    scc_chunk.py      изъятие ядра, сшивка, гейт         (без LLM)
    scc_usability.py  проверка пригодности ядра          (LLM)
    prompts/          промты трёх этапов
    schemas/          контракт чанка (chunk.schema.json)
"""

