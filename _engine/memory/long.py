"""
SCC — долгая память
====================

Архив чанков, вынесенных из контекста (METHODOLOGY_MEMORY.md §1). В контекст
попадает **только инструкция** с номером последнего чанка; содержимое — через
Архивариуса.

ЧЕГО ЗДЕСЬ НЕТ
---------------
Модуль **не возвращает чанки в среднюю память**. Переход «долгая -> средняя» не
существует: повторная свёртка чанков запрещена (инвариант 2), а возврат в стак
означал бы, что чанк снова может попасть под свёртку. Архивариус только читает.

Модуль **не сжимает** и **не обрабатывает LLM**. Вынос — смена уровня в
chain.json, больше ничего.

    long_memory = LongMemory(stack)
    long_memory.after_accept(stack, [1, 2, 3])   # вызвал move_to_long
    long_memory.instruction()                    # текст для контекста
    long_memory.read(2)                          # чанк из архива (для Архивариуса)
"""

from __future__ import annotations

from memory import tokens
from memory.config import MemoryConfig
from memory.stack import ChunkError, ChunkStack

# ── Шаблон инструкции ────────────────────────────────────────────────────────
# Инструкция — ЧАСТЬ HEAD (METHODOLOGY_HEAD.md §4.1): она стоит в начале
# контекста, не сжимается и не уходит в архив. Поэтому формулировка обязана
# быть исполнимой: агент видит не «архив существует», а КОНКРЕТНЫЕ команды.
#
# Три обязательные части (по методологии):
#   1. что доступно — номера чанков и граница;
#   2. как пользоваться — какие функции вызывать;
#   3. чего НЕ делать — запреты, включая разграничение с CAS.
#
# ПОЧЕМУ ЗАПРЕТЫ ЯВНЫЕ. Архивариус — агент с LLM, и соблазн «спросить его обо
# всём» велик. Но его ответ проходит через генерацию и искажает точные значения,
# поэтому в инструкции прямо сказано: точные данные — область CAS, не архива.
INSTRUCTION_TEMPLATE = """[HEAD · АРХИВАРИУС] Разведка АРХИВА ЧАНКОВ (только чтение).

Архив содержит чанки 1..{last}. Они вынесены из контекста, но НЕ потеряны.

ЧТО ДОСТУПНО:
    long.read(N)        -> содержимое чанка N  (N в диапазоне 1..{last})
    long.chunks()       -> список архивных чанков по возрастанию номера
    long.last_number()  -> номер последнего архивного чанка
    long.is_empty()     -> пуст ли архив

КАК ПОЛЬЗОВАТЬСЯ:
    Нужна история, которой нет в контексте -> запроси long.read(N)
    по конкретному номеру. Сначала посмотри long.chunks(), чтобы понять,
    какие номера существуют.

ЧЕГО НЕ ДЕЛАТЬ:
    не переписывать и не сжимать архивные чанки — запрещено (инвариант 2);
    не возвращать чанк в среднюю память — такого перехода не существует;
    не запрашивать весь архив целиком: это вернёт контекст, который только
    что был вынесен, и сведёт на нет всю экономию;
    НЕ ЗАПРАШИВАТЬ ТОЧНЫЕ ДАННЫЕ ПО ССЫЛКАМ CAS?{{хеш}}? — это область CAS,
    а не архива. Архивариус отвечает пересказом и исказил бы значения."""


class LongMemory:
    """
    Долгая память: архив чанков.

    Сам архив — это чанки с `level: long` в общем стеке. Класс отвечает за
    инструкцию для контекста и за чтение по запросу (для Архивариуса).
    """

    def __init__(self, stack: ChunkStack, config: MemoryConfig | None = None) -> None:
        self.stack = stack
        self.config = config

    def after_accept(self, stack: ChunkStack, numbers: list[int]) -> None:
        """
        Завершить вынос: зафиксировать факт архивации.

        Отдельный метод, а не побочный эффект `move_to_long`: вызывающий должен
        явно видеть, что переход завершён. Здесь же — место для будущей
        синхронизации с базой CAS (сейчас её нет).

        ФАКТ АРХИВАЦИИ ЧИТАЕТСЯ ИЗ СТЕКА, а не хранится в поле. Прежде здесь
        было `self._archived = ...` — поле, которое **нигде не читалось** и
        при частичном выносе **затирало** историю: каждый вызов перезаписывал
        список одним номером. Единственный источник правды об уровнях —
        `chain.json` (инвариант 6), поэтому и факт архивации берётся оттуда.
        """
        # Номера, реально находящиеся в архиве: источник правды — стек.
        archived = {entry["n"] for entry in stack.long()}
        missing = [n for n in numbers if n not in archived]
        if missing:
            raise ChunkError(
                f"чанки {missing} объявлены вынесенными, но в архиве их нет: "
                "состояние расходится (инвариант 6)"
            )

    def chunks(self) -> list[dict]:
        """Записи архивных чанков по возрастанию номера."""
        return self.stack.long()

    def read(self, n: int) -> dict:
        """
        Прочитать чанк из архива по номеру.

        Это точка входа для Архивариуса: он читает по запросу агента. Метод
        только читает — переписать или сжать чанк нельзя (инвариант 7).
        """
        entry = next((e for e in self.stack.long() if e["n"] == n), None)
        if entry is None:
            raise KeyError(f"чанк n={n} не найден в архиве")
        return self.stack.load(n)

    def content(self) -> str:
        """
        Содержимое ВСЕГО архива.

        ВНИМАНИЕ: этот метод существует для замеров и отладки. В контекст
        агента архивное содержимое НЕ попадает — только инструкция. Вызов в
        рабочем пути означал бы нарушение схемы уровней.
        """
        return self.stack.content_of_level("long")

    def token_count(self) -> int:
        """Объём архива в токенах (для замеров, не для контекста)."""
        return tokens.estimate(self.content())

    def instruction(self) -> str:
        """
        Текст инструкции для контекста.

        Пустая строка, если архив пуст: упоминать несуществующий архив вредно —
        агент начнёт запрашивать то, чего нет.
        """
        last = self.last_number()
        if last == 0:
            return ""
        return INSTRUCTION_TEMPLATE.format(last=last)

    def last_number(self) -> int:
        """Номер последнего архивного чанка. 0, если архив пуст."""
        archive = self.stack.long()
        return max((entry["n"] for entry in archive), default=0)

    def is_empty(self) -> bool:
        """Пуст ли архив."""
        return not self.stack.long()

    def __len__(self) -> int:
        """Число чанков в архиве."""
        return len(self.stack.long())
